#!/usr/bin/env bash
# .devcontainer/postCreate.sh
#
# Runs automatically after the dev container is created (postCreateCommand).
# Idempotent — safe to re-run at any time.
#
# Steps:
#   1. Bootstrap .env (copy .env.example, or write devcontainer defaults)
#   2. Wait for PostgreSQL to be ready
#   3. Build the Rust workspace (cargo build)
#   4. Run all pending SQLx migrations
#   5. Seed the database with representative development data
#   6. Install Node dependencies for the frontend and SDKs

set -euo pipefail

CYAN='\033[0;36m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m' # No Color

info()    { echo -e "${CYAN}[devcontainer]${NC} $*"; }
success() { echo -e "${GREEN}[devcontainer]${NC} ✓ $*"; }
warn()    { echo -e "${YELLOW}[devcontainer]${NC} ⚠ $*"; }
error()   { echo -e "${RED}[devcontainer]${NC} ✗ $*" >&2; }

WORKSPACE="/workspaces/SorobanPulse"
cd "$WORKSPACE"

# ── 1. Bootstrap .env ─────────────────────────────────────────────────────────
if [ ! -f .env ]; then
  if [ -f .env.example ]; then
    info "Copying .env.example to .env…"
    cp .env.example .env
    success ".env created from .env.example"
  else
    info "Creating .env from devcontainer defaults…"
    cat > .env <<'EOF'
# ── Dev Container environment ─────────────────────────────────────────────────
# Auto-generated by .devcontainer/postCreate.sh
# Edit freely — this file is gitignored.

DATABASE_URL=postgres://soroban:soroban@db:5432/soroban_pulse
STELLAR_RPC_URL=https://soroban-testnet.stellar.org
ALLOW_INSECURE_RPC=true
START_LEDGER=0
PORT=3000
RUST_LOG=info
ENVIRONMENT=development
ALLOWED_ORIGINS=*
DB_MAX_CONNECTIONS=10
DB_MIN_CONNECTIONS=2
RATE_LIMIT_PER_MINUTE=0
EOF
    success ".env created from devcontainer defaults"
  fi
else
  info ".env already exists — skipping"
fi

# ── 2. Wait for PostgreSQL ────────────────────────────────────────────────────
info "Waiting for PostgreSQL to be ready…"
MAX_ATTEMPTS=30
ATTEMPT=0
until pg_isready -h db -U soroban -d soroban_pulse -q 2>/dev/null; do
  ATTEMPT=$((ATTEMPT + 1))
  if [ "$ATTEMPT" -ge "$MAX_ATTEMPTS" ]; then
    error "PostgreSQL did not become ready after ${MAX_ATTEMPTS} attempts."
    error "Is the db service running? Try: docker compose up db"
    exit 1
  fi
  sleep 2
done
success "PostgreSQL is ready"

# ── 3. Build the Rust workspace ───────────────────────────────────────────────
info "Building the Rust workspace (cargo build)…"
if cargo build 2>&1; then
  success "cargo build completed"
else
  error "cargo build failed. Check the output above."
  exit 1
fi

# ── 4. Run migrations ─────────────────────────────────────────────────────────
info "Running SQLx migrations…"
export DATABASE_URL="postgres://soroban:soroban@db:5432/soroban_pulse"

if cargo sqlx migrate run 2>&1; then
  success "Migrations applied"
else
  warn "Migration command failed — attempting with sqlx-cli directly"
  if sqlx migrate run --database-url "$DATABASE_URL" 2>&1; then
    success "Migrations applied via sqlx-cli"
  else
    error "Migrations failed. Check the output above."
    exit 1
  fi
fi

# ── 5. Seed development data ──────────────────────────────────────────────────
info "Seeding development data…"

# Use the seed binary to insert realistic events, subscriptions, notification
# channels, and contract labels.  The binary is idempotent (ON CONFLICT DO
# NOTHING) and configurable: set EVENTS= to change the volume.
if DATABASE_URL="$DATABASE_URL" make seed EVENTS="${SEED_EVENTS:-500}" 2>&1; then
  success "Database seeded with representative development data"
else
  warn "make seed failed — the service will still start, just with an empty database"
fi

# ── 6. Node dependencies ──────────────────────────────────────────────────────
info "Installing Node dependencies for frontend…"
if [ -f frontend/package.json ]; then
  (cd frontend && npm ci --prefer-offline 2>&1 | tail -5) && \
    success "frontend/ Node modules installed"
else
  warn "frontend/package.json not found — skipping"
fi

if [ -f web/package.json ]; then
  info "Installing Node dependencies for web/…"
  (cd web && npm ci --prefer-offline 2>&1 | tail -5) && \
    success "web/ Node modules installed"
fi

# ── Done ──────────────────────────────────────────────────────────────────────
echo ""
echo -e "${GREEN}════════════════════════════════════════════════════${NC}"
echo -e "${GREEN}  SorobanPulse dev container is ready! 🚀${NC}"
echo -e "${GREEN}════════════════════════════════════════════════════${NC}"
echo ""
echo "  Start the API:           make run"
echo "  Run tests:               make test"
echo "  Start frontend:          cd frontend && npm run dev"
echo "  List all make targets:   make help"
echo ""
