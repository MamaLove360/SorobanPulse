/// Errors originating from database operations.
#[derive(Debug, Error)]
pub enum DatabaseError {
    #[error("Query failed: {0}")]
    QueryFailed(#[from] sqlx::Error),

    #[error("Query timed out")]
    Timeout,

    #[error("Record not found: {0}")]
    NotFound(String),

    #[error("Unique constraint violation: {0}")]
    UniqueViolation(String),

    #[error("Connection pool exhausted")]
    PoolExhausted,
}

/// Errors originating from the background indexer.
#[derive(Debug, Error)]
pub enum IndexerError {
    #[error("RPC call failed: {0}")]
    RpcCallFailed(String),

    #[error("Ledger gap detected: expected {expected}, got {got}")]
    LedgerGap { expected: u64, got: u64 },

    #[error("Advisory lock not acquired")]
    LockNotAcquired,

    #[error("Indexer stalled: last ledger {last_ledger}")]
    Stalled { last_ledger: u64 },
}

/// Errors originating from webhook delivery.
#[derive(Debug, Error)]
pub enum WebhookError {
    #[error("Delivery failed after {attempts} attempts: {reason}")]
    DeliveryFailed { attempts: u32, reason: String },

    #[error("Invalid endpoint URL: {0}")]
    InvalidEndpoint(String),

    #[error("HMAC signature mismatch")]
    SignatureMismatch,
}

/// Errors originating from subscription management.
#[derive(Debug, Error)]
pub enum SubscriptionError {
    #[error("Subscription not found: {0}")]
    NotFound(String),

    #[error("Invalid filter: {0}")]
    InvalidFilter(String),

    #[error("Subscription limit exceeded")]
    LimitExceeded,
}

/// Authentication and authorisation errors.
#[derive(Debug, Error)]
pub enum AuthError {
    #[error("Missing or invalid API key")]
    Unauthenticated,

    #[error("Insufficient privileges: {0}")]
    Forbidden(String),

    #[error("Token expired")]
    TokenExpired,
}

/// Errors from external RPC / network calls.
#[derive(Debug, Error)]
pub enum RpcError {
    #[error("Network error: {0}")]
    Network(#[from] reqwest::Error),

    #[error("Unexpected response: {0}")]
    UnexpectedResponse(String),

    #[error("Rate limited by upstream")]
    RateLimited,
}

/// Errors raised while constructing long-lived components (HTTP clients,
/// in-memory filters, exporters). These replace the `expect()` calls that
/// previously aborted the process on construction failure (issue #1246).
#[derive(Debug, Error)]
pub enum InitError {
    #[error("Failed to build {component} HTTP client: {source}")]
    HttpClient {
        component: &'static str,
        #[source]
        source: reqwest::Error,
    },

    #[error("Invalid {component} configuration: {reason}")]
    InvalidConfig {
        component: &'static str,
        reason: String,
    },
}

impl InitError {
    pub fn invalid_config(component: &'static str, reason: impl Into<String>) -> Self {
        Self::InvalidConfig {
            component,
            reason: reason.into(),
        }
    }
}

